def make_po(lang_code, idx):
    po = polib.POFile()
    po.metadata = {
        'Project-Id-Version': 'UyIjara 1.0',
        'Report-Msgid-Bugs-To': '',
        'PO-Revision-Date': '2025-01-01 00:00+0500',
        'Last-Translator': 'UyIjara',
        'Language-Team': lang_code,
        'Language': lang_code,
        'MIME-Version': '1.0',
        'Content-Type': 'text/plain; charset=UTF-8',
        'Content-Transfer-Encoding': '8bit',
        'Plural-Forms': 'nplurals=2; plural=(n != 1);',
    }

    seen = set()
    for entry in TRANSLATIONS:
        msgid = entry[0]
        if msgid in seen:
            continue
        seen.add(msgid)
        msgstr = entry[idx]
        po.append(polib.POEntry(msgid=msgid, msgstr=msgstr))

    out_dir = os.path.join(BASE, lang_code, 'LC_MESSAGES')
    os.makedirs(out_dir, exist_ok=True)
    po_path = os.path.join(out_dir, 'django.po')
    mo_path = os.path.join(out_dir, 'django.mo')
    po.save(po_path)
    po.save_as_mofile(mo_path)
    print(f'wrote {po_path} ({len(po)} entries)')


